// Build-time plugin loader. Runs before `next dev` / `next build`. No framework: one file, plain imports.
// Only ENABLED plugins are bundled. Enabled = env PLUGINS ("chat,usage" or "all" or "none"), else the on/off saved in
// Settings (config.settings.plugins in the database, read here at build time), else each plugin.json "enabled".
// Writes (all committed, so a build without this step still works):
//   index.gen.js    pages, settings and APIs of bundled plugins
//   config.gen.js   pure settings files (DEFAULTS, RULES) of bundled plugins
//   catalog.gen.js  every plugin.json found (bundled or not), for the Settings list and trust prompt
import fs from "fs"; import path from "path"; import { fileURLToPath } from "url";
const here=path.dirname(fileURLToPath(import.meta.url));
// Official = shipped in this repo by its maintainer. Anything else gets a third-party warning before it is turned on.
const OFFICIAL={chat:"Adam Siwiec",usage:"Adam Siwiec","worker-tasks":"Adam Siwiec"};
const dirs=fs.readdirSync(here).filter(d=>fs.existsSync(path.join(here,d,"plugin.json"))).sort();
const man=Object.fromEntries(dirs.map(d=>{ const m=JSON.parse(fs.readFileSync(path.join(here,d,"plugin.json"),"utf8"));
  if(m.name!==d) throw new Error(`plugins/${d}/plugin.json: name must be "${d}"`);
  if(!/^[a-z0-9-]{2,40}$/.test(d)) throw new Error(`plugins/${d}: name must be lowercase letters, digits, dashes`);
  return [d,m]; }));
async function saved(){ // the Settings on/off, or null when there is no database to ask
  const url=process.env.DATABASE_URL; if(!url||["1","true"].includes(process.env.DEMO_MODE)) return null;
  try{ const { default: pg }=await import("pg"); const c=new pg.Client({connectionString:url,connectionTimeoutMillis:8000,ssl:/sslmode=disable|localhost|127\.0\.0\.1/.test(url)?false:{rejectUnauthorized:false}});
    await c.connect(); try{ const r=await c.query("select value->'plugins' p from config where key='settings'"); return r.rows[0]?.p||{}; } finally{ await c.end(); } }
  catch(e){ console.log(`plugins: could not read Settings from the database (${e.code||e.message}); using plugin.json defaults`); return null; } }
let on, why;
const env=(process.env.PLUGINS||"").trim();
if(env){ const l=env.split(",").map(s=>s.trim()); on=d=>l.includes("all")||l.includes(d); why="PLUGINS env"; }
else{ const s=await saved(); on=d=>(s||{})[d]??man[d].enabled!==false; why=s?"Settings in the database":"plugin.json defaults"; }
const bundled=dirs.filter(on);
const imp=[], list=[], cimp=[], clist=[];
bundled.forEach((d,i)=>{ const m=man[d], has=f=>fs.existsSync(path.join(here,d,f));
  const e=[`...${JSON.stringify({name:m.name,title:m.title||m.name,description:m.description||"",enabled:m.enabled!==false,provides:m.provides||[]})}`];
  if(has("page.js")){ imp.push(`import Page${i} from "./${d}/page.js";`); e.push(`Page:Page${i}`); }
  if(has("settings.js")){ imp.push(`import Settings${i} from "./${d}/settings.js";`); e.push(`Settings:Settings${i}`); }
  if(has("config.js")){ cimp.push(`import * as c${i} from "./${d}/config.js";`); clist.push(`  ${JSON.stringify(d)}:c${i},`); }
  if(has("api.js")){ imp.push(`import * as api${i} from "./${d}/api.js";`); e.push(`api:api${i}`); }
  list.push(`  {${e.join(", ")}},`); });
const H=f=>`// Generated by plugins/load.mjs from ${f}. Do not edit; run \`node plugins/load.mjs\`.\n`;
const out=`${H("plugins/*/plugin.json")}${imp.join("\n")}\nexport const PLUGINS=[\n${list.join("\n")}\n];\n`;
const cout=`${H("plugins/*/config.js")}${cimp.join("\n")}\nexport const CONFIGS={\n${clist.join("\n")}\n};\n`;
const cat=dirs.map(d=>{ const m=man[d], off=OFFICIAL[d]&&m.author===OFFICIAL[d];
  return {name:d,title:m.title||d,description:m.description||"",enabled:m.enabled!==false,author:m.author||"unknown",official:!!off,bundled:bundled.includes(d)}; });
const kout=`${H("plugins/*/plugin.json")}export const CATALOG=${JSON.stringify(cat,null,1)};\n`;
const w=(n,t)=>{ const f=path.join(here,n); if(!fs.existsSync(f)||fs.readFileSync(f,"utf8")!==t){ fs.writeFileSync(f,t); return true; } };
w("index.gen.js",out); w("config.gen.js",cout); w("catalog.gen.js",kout);
console.log(`plugins: bundling ${bundled.join(", ")||"none"} (from ${why})`);
