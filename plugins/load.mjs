// Build-time plugin loader. Reads plugins/*/plugin.json and writes plugins/index.gen.js (committed, so a build
// without this step still works). Runs before `next dev` / `next build`. No framework: one file, plain imports.
import fs from "fs"; import path from "path"; import { fileURLToPath } from "url";
const here=path.dirname(fileURLToPath(import.meta.url));
const dirs=fs.readdirSync(here).filter(d=>fs.existsSync(path.join(here,d,"plugin.json"))).sort();
const imp=[], list=[];
dirs.forEach((d,i)=>{
  const m=JSON.parse(fs.readFileSync(path.join(here,d,"plugin.json"),"utf8"));
  if(m.name!==d) throw new Error(`plugins/${d}/plugin.json: name must be "${d}"`);
  if(!/^[a-z0-9-]{2,40}$/.test(d)) throw new Error(`plugins/${d}: name must be lowercase letters, digits, dashes`);
  const has=f=>fs.existsSync(path.join(here,d,f));
  const e=[`...${JSON.stringify({name:m.name,title:m.title||m.name,description:m.description||"",enabled:m.enabled!==false,provides:m.provides||[]})}`];
  if(has("page.js")){ imp.push(`import Page${i} from "./${d}/page.js";`); e.push(`Page:Page${i}`); }
  if(has("api.js")){ imp.push(`import * as api${i} from "./${d}/api.js";`); e.push(`api:api${i}`); }
  list.push(`  {${e.join(", ")}},`);
});
const out=`// Generated by plugins/load.mjs from plugins/*/plugin.json. Do not edit; run \`node plugins/load.mjs\`.\n${imp.join("\n")}\nexport const PLUGINS=[\n${list.join("\n")}\n];\n`;
const f=path.join(here,"index.gen.js"); if(!fs.existsSync(f)||fs.readFileSync(f,"utf8")!==out){ fs.writeFileSync(f,out); console.log(`plugins: ${dirs.join(", ")||"none"}`); }
